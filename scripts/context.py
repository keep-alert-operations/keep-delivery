"""Offline, repository-native task routing and bounded authoritative reading.

The catalog supplies navigation, never permission or a completeness guarantee.
No commands from the catalog are executed. Only explicit ``render`` writes files.
"""
from __future__ import annotations

import argparse
import fnmatch
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import re
import sys
import unicodedata
from urllib.parse import quote


REPOSITORIES = frozenset(f"appchi-{name}" for name in (
    "frontend", "api", "ingestion", "processor", "correlation", "indexer",
    "domain", "contracts", "migrations", "delivery", "design",
))
AUTHORITIES = frozenset((
    "instruction", "normative", "scope", "verification", "implementation", "evidence", "historical",
))
CATALOG = "appchi-design/context/task-map.json"
EVALUATIONS = "appchi-design/context/evaluation-cases.json"
GENERATED = "<!-- Generated by appchi-delivery/scripts/context.py; edit task-map.json instead. -->"
GUIDANCE = (
    "Candidate reading plan only: matching does not establish completeness. Read applicable "
    "workspace/repository instructions, inspect actual callers and source indexes, resolve "
    "scope corrections, and expand when new dependencies or uncertainty appear. Stop initial "
    "exploration only when behavior, constraints, affected boundaries and verification are clear."
)


class ContextError(ValueError):
    """An invalid or unavailable context input; never an empty successful result."""


def fail(message):
    raise ContextError(message)


def relative_path(value):
    if not isinstance(value, str) or not value or "\\" in value:
        fail(f"Expected a workspace-relative POSIX path: {value!r}")
    parts = PurePosixPath(value).parts
    if (value.startswith("/") or ":" in value or any(p in ("..", ".") for p in value.split("/"))
            or not parts or parts[0] not in REPOSITORIES):
        fail(f"Path must stay in a declared Appchi repository: {value!r}")
    return parts


def safe_path(workspace, value, *, must_exist=True):
    parts = relative_path(value)
    candidate = workspace.joinpath(*parts)
    resolved = candidate.resolve()
    try:
        resolved.relative_to(workspace / parts[0])
    except ValueError:
        fail(f"Path escapes its declared workspace repository: {value}")
    if must_exist and not resolved.is_file():
        fail(f"Missing or non-regular file: {value}; inspect source indexes and checkout state")
    return resolved


def json_file(workspace, value):
    try:
        return json.loads(safe_path(workspace, value).read_text(encoding="utf-8-sig"))
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        fail(f"Cannot read {value}: {exc}")


def strings(value, label, *, nonempty=False):
    if (not isinstance(value, list) or any(not isinstance(v, str) or not v.strip() for v in value)
            or len(set(value)) != len(value) or (nonempty and not value)):
        fail(f"{label} must be a {'nonempty ' if nonempty else ''}list of unique nonempty strings")


def identifier(value, label):
    if not isinstance(value, str) or not re.fullmatch(r"[a-z0-9]+(?:[-_][a-z0-9]+)*", value):
        fail(f"Invalid {label}: {value!r}")


def slug(title):
    """GitHub-style Unicode heading anchor, with duplicate suffixes added by headings()."""
    value = re.sub(r"<[^>]+>", "", title)
    value = re.sub(r"!?\[([^\]]+)\]\([^)]*\)", r"\1", value).lower()
    return "".join(
        "-" if ch.isspace() else ch for ch in value
        if ch.isspace() or ch in "-_" or unicodedata.category(ch)[0] in "LNM"
    )


def headings(lines):
    """Parse ATX/setext headings while ignoring fenced and indented code."""
    result, anchors = [], set()
    fence, previous = None, None
    for index, line in enumerate(lines):
        marker = re.match(r"^ {0,3}(`{3,}|~{3,})(.*)$", line.rstrip("\r\n"))
        if fence:
            if (marker and marker[1][0] == fence[0] and len(marker[1]) >= len(fence)
                    and not marker[2].strip()):
                fence = None
            previous = None
            continue
        if marker:
            fence, previous = marker[1], None
            continue
        match = re.match(r"^ {0,3}(#{1,6})(?:[ \t]+(.*?)|[ \t]*)$", line.rstrip("\r\n"))
        underline = re.match(r"^ {0,3}(=+|-+)\s*$", line.rstrip("\r\n"))
        if match:
            level, title, start = len(match[1]), re.sub(r"[ \t]+#+[ \t]*$", "", match[2] or ""), index
        elif underline and previous is not None:
            level, title, start = (1 if underline[1][0] == "=" else 2), previous[1], previous[0]
        else:
            previous = ((index, line.strip()) if line.strip() and not line.startswith(("    ", "\t"))
                        else None)
            continue
        base, suffix = slug(title), 0
        anchor = base
        while anchor in anchors:
            suffix += 1
            anchor = f"{base}-{suffix}"
        anchors.add(anchor)
        result.append({"title": title, "level": level, "start": start, "anchor": anchor})
        previous = None
    for index, heading in enumerate(result):
        heading["end"] = next((h["start"] for h in result[index + 1:]
                               if h["level"] <= heading["level"]), len(lines))
    return result


def merged_ranges(ranges):
    result = []
    for start, end in sorted(ranges):
        if end <= start:
            continue
        if result and start <= result[-1][1]:
            result[-1] = (result[-1][0], max(result[-1][1], end))
        else:
            result.append((start, end))
    return result


class Context:
    def __init__(self, workspace):
        self.workspace = Path(workspace).resolve()
        if not self.workspace.is_dir():
            fail(f"Workspace directory does not exist: {workspace}")
        self.catalog = json_file(self.workspace, CATALOG)
        self.validate_schema()

    def validate_schema(self):
        data = self.catalog
        if (not isinstance(data, dict) or type(data.get("schema_version")) is not int
                or data["schema_version"] != 1):
            fail("Catalog schema_version must be 1")
        if not isinstance(data.get("sources"), dict) or not data["sources"]:
            fail("Catalog sources must be a nonempty object")
        if not isinstance(data.get("routes"), list) or not data["routes"]:
            fail("Catalog routes must be a nonempty list")
        for source_id, source in data["sources"].items():
            identifier(source_id, "source ID")
            if not isinstance(source, dict):
                fail(f"Source {source_id} must be an object")
            relative_path(source.get("path"))
            if not isinstance(source.get("authority"), str) or source["authority"] not in AUTHORITIES:
                fail(f"Source {source_id} has invalid authority")
            strings(source.get("sections"), f"Source {source_id} sections")
            if source.get("include_preamble") is not True:
                fail(f"Source {source_id} must include_preamble: true to preserve scope corrections")
        self.routes = {}
        for route in data["routes"]:
            if not isinstance(route, dict):
                fail("Each route must be an object")
            route_id = route.get("id")
            identifier(route_id, "route ID")
            if route_id in self.routes:
                fail(f"Duplicate route ID: {route_id}")
            if not isinstance(route.get("title"), str) or not route["title"].strip():
                fail(f"Route {route_id} needs a title")
            for field in ("when", "keywords", "path_globs", "requires", "sources", "repositories", "checks"):
                strings(route.get(field), f"Route {route_id} {field}", nonempty=field == "when")
            for pattern in route["path_globs"]:
                parts = PurePosixPath(pattern).parts
                if ("\\" in pattern or ":" in pattern or pattern.startswith("/")
                        or any(p in ("..", ".") for p in pattern.split("/"))
                        or not parts or not any(fnmatch.fnmatchcase(repo, parts[0]) for repo in REPOSITORIES)):
                    fail(f"Route {route_id} has unsafe path glob: {pattern}")
            for repo in route["repositories"]:
                if repo not in REPOSITORIES:
                    fail(f"Route {route_id} has undeclared repository {repo}")
            if not isinstance(route.get("expand"), list):
                fail(f"Route {route_id} expand must be a list")
            for expansion in route["expand"]:
                if (not isinstance(expansion, dict) or not isinstance(expansion.get("when"), str)
                        or not expansion["when"].strip()):
                    fail(f"Route {route_id} expansion needs a condition")
                identifier(expansion.get("route"), "expansion route")
            self.routes[route_id] = route
        for route in self.routes.values():
            for source_id in route["sources"]:
                if source_id not in data["sources"]:
                    fail(f"Route {route['id']} references unknown source: {source_id}")
            for route_id in route["requires"] + [x["route"] for x in route["expand"]]:
                if route_id not in self.routes:
                    fail(f"Route {route['id']} references unknown route: {route_id}")
        self.closure(list(self.routes))

    def closure(self, selected):
        result, active, done = [], set(), set()

        def visit(route_id):
            if route_id not in self.routes:
                fail(f"Unknown route: {route_id}; use list and inspect source indexes")
            if route_id in active:
                fail(f"Required-route cycle involving {route_id}")
            if route_id in done:
                return
            active.add(route_id)
            for dependency in self.routes[route_id]["requires"]:
                visit(dependency)
            active.remove(route_id)
            done.add(route_id)
            result.append(route_id)

        for route_id in selected:
            visit(route_id)
        return result

    def source(self, source_id):
        if source_id not in self.catalog["sources"]:
            fail(f"Unknown source: {source_id}")
        source = self.catalog["sources"][source_id]
        path = safe_path(self.workspace, source["path"])
        try:
            content = path.read_bytes()
            lines = content.decode("utf-8-sig").replace("\r\n", "\n").replace("\r", "\n").splitlines(keepends=True)
        except (OSError, UnicodeError) as exc:
            fail(f"Cannot read source {source_id}: {exc}")
        parsed = headings(lines)
        selected = []
        for title in source["sections"]:
            matches = [h for h in parsed if h["title"] == title]
            if len(matches) != 1:
                fail(f"Source {source_id}: heading {title!r} must exist exactly once (found {len(matches)})")
            selected.append(matches[0])
        preamble_end = next((h["start"] for h in parsed if h["level"] == 2), len(lines))
        ranges = ([(0, len(lines))] if not selected else
                  merged_ranges([(0, preamble_end)] + [(h["start"], h["end"]) for h in selected]))
        return {
            "id": source_id, "path": source["path"], "authority": source["authority"],
            "sha256": hashlib.sha256(content).hexdigest(), "include_preamble": True,
            "preamble_lines": [1, preamble_end] if preamble_end else [],
            "sections": [{"title": h["title"], "line": h["start"] + 1,
                          "end_line": h["end"], "anchor": h["anchor"]} for h in selected],
            "ranges": [[start + 1, end] for start, end in ranges],
            "content": "\n\n<!-- Unselected sections omitted. -->\n\n".join(
                "".join(lines[start:end]) for start, end in ranges),
        }

    def plan(self, *, routes=(), task="", paths=()):
        reasons, suggestions = {}, {}
        normalized_paths = []
        for path in paths:
            normalized = path.replace("\\", "/")
            relative_path(normalized)
            safe_path(self.workspace, normalized, must_exist=False)
            normalized_paths.append(normalized)
        for route_id in routes:
            if route_id not in self.routes:
                fail(f"Unknown route: {route_id}; use list and inspect source indexes")
            reasons.setdefault(route_id, []).append("Explicit route")
        for route_id, route in self.routes.items():
            for keyword in route["keywords"]:
                if re.search(r"(?<!\w)" + re.escape(keyword) + r"(?!\w)", task, re.IGNORECASE):
                    suggestions.setdefault(route_id, []).append(f"Task phrase: {keyword}")
            for path in normalized_paths:
                for pattern in route["path_globs"]:
                    if fnmatch.fnmatchcase(path.casefold(), pattern.casefold()):
                        suggestions.setdefault(route_id, []).append(f"Path: {path} matches {pattern}")
        if not routes:
            reasons.update(suggestions)
        selected = self.closure(reasons)
        for route_id in selected:
            for required in self.routes[route_id]["requires"]:
                reasons.setdefault(required, []).append(f"Required by: {route_id}")
        source_reasons, repositories, checks, expansions = {}, [], [], []
        for route_id in selected:
            route = self.routes[route_id]
            for source_id in route["sources"]:
                source_reasons.setdefault(source_id, []).append(route_id)
            for repo in route["repositories"]:
                if repo not in repositories:
                    repositories.append(repo)
            for check in route["checks"]:
                if check not in checks:
                    checks.append(check)
            expansions.extend({"from": route_id, "when": item["when"], "route": item["route"],
                               "already_selected": item["route"] in selected} for item in route["expand"])
        sources = []
        for source_id, used_by in source_reasons.items():
            source = self.source(source_id)
            source.pop("content")
            source["required_by"] = used_by
            sources.append(source)
        return {
            "schema_version": 1, "status": "candidate" if selected else "unresolved",
            "task": task, "paths": normalized_paths, "guidance": GUIDANCE,
            "unresolved": [] if selected else [
                "No task route matched. Inspect repository instructions and source indexes; "
                "choose explicit routes or extend the map before treating the reading plan as sufficient."],
            "routes": [{"id": rid, "title": self.routes[rid]["title"], "reasons": reasons[rid]}
                       for rid in selected],
            "suggestions": [{"id": rid, "title": self.routes[rid]["title"], "reasons": why}
                            for rid, why in suggestions.items() if rid not in selected],
            "sources": sources, "repositories": repositories, "checks": checks,
            "conditional_expansions": expansions,
        }

    def evaluations(self):
        fixture = json_file(self.workspace, EVALUATIONS)
        if (not isinstance(fixture, dict) or type(fixture.get("schema_version")) is not int
                or fixture["schema_version"] != 1
                or not isinstance(fixture.get("cases"), list) or len(fixture["cases"]) < 20):
            fail("Evaluation fixtures need schema_version 1 and at least 20 cases")
        ids, errors = set(), []
        for case in fixture["cases"]:
            if not isinstance(case, dict):
                fail("Evaluation case must be an object")
            identifier(case.get("id"), "evaluation ID")
            if case["id"] in ids:
                fail(f"Duplicate evaluation ID: {case['id']}")
            ids.add(case["id"])
            if not isinstance(case.get("task"), str):
                fail(f"Evaluation {case['id']} task must be text")
            for field in ("paths", "routes", "must_include_routes", "must_exclude_routes", "must_include_sources"):
                strings(case.get(field), f"Evaluation {case['id']} {field}")
            for field in ("routes", "must_include_routes", "must_exclude_routes"):
                for route_id in case[field]:
                    if route_id not in self.routes:
                        fail(f"Evaluation {case['id']} references unknown route: {route_id}")
            for source_id in case["must_include_sources"]:
                if source_id not in self.catalog["sources"]:
                    fail(f"Evaluation {case['id']} references unknown source: {source_id}")
            plan = self.plan(routes=case["routes"], task=case["task"], paths=case["paths"])
            actual_routes = {r["id"] for r in plan["routes"]}
            actual_sources = {s["id"] for s in plan["sources"]}
            for field, missing in (
                ("missing routes", set(case["must_include_routes"]) - actual_routes),
                ("forbidden routes", set(case["must_exclude_routes"]) & actual_routes),
                ("missing sources", set(case["must_include_sources"]) - actual_sources),
            ):
                if missing:
                    errors.append(f"{case['id']}: {field}: {', '.join(sorted(missing))}")
        if errors:
            fail("Routing evaluation failed:\n" + "\n".join(errors))
        return len(ids)

    def generated_documents(self):
        result = {}
        map_lines = ["---", "tags: [context-map]", "---", "", GENERATED, "", "# Appchi task map", "",
                     GUIDANCE, "", "Required links are mandatory reading dependencies. Conditional "
                     "links identify when to expand; they are not automatically selected.", "",
                     "Open the workspace root as an Obsidian vault to include sibling repositories. "
                     "Use a route's local graph for a focused neighborhood; graph edges alone do "
                     "not encode the conditions below.", "", "| Route | Applies when |", "|---|---|"]
        for route_id, route in self.routes.items():
            path = f"appchi-design/context/routes/{route_id}.md"
            lines = ["---", "tags: [context-route]", f"route_id: {route_id}", "---", "", GENERATED,
                     "", f"# {route['title']}", "", "[Task map](../map.md)", "", "## Applies when", ""]
            lines.extend(f"- {condition}" for condition in route["when"])
            lines.extend(["", "## Required routes", ""])
            lines.extend([f"- [{self.routes[rid]['title']}]({rid}.md)" for rid in route["requires"]]
                         or ["No additional route prerequisites."])
            lines.extend(["", "## Required sources", "", "Include each source's preamble and scope "
                          "corrections, plus the selected sections and their subsections.", ""])
            for source_id in route["sources"]:
                source = self.source(source_id)
                link = os.path.relpath(self.workspace / source["path"],
                                       (self.workspace / path).parent).replace("\\", "/")
                lines.append(f"- [{source_id}]({quote(link, safe='/.-_')}) — {source['authority']}; "
                             "preamble required.")
                if source["sections"]:
                    lines.extend(f"  - [{s['title']}]({quote(link, safe='/.-_')}#{quote(s['anchor'])})"
                                 for s in source["sections"])
                else:
                    lines.append("  - Read the full source.")
            lines.extend(["", "## Conditional expansion", ""])
            lines.extend([f"- When {item['when']}: [{self.routes[item['route']]['title']}]({item['route']}.md)."
                          for item in route["expand"]] or ["Expand through source indexes if dependencies or uncertainty emerge."])
            lines.extend(["", "## Repositories to inspect", ""])
            lines.extend([f"- [{repo} instructions](../../../{repo}/AGENTS.md)" for repo in route["repositories"]]
                         or ["Determine affected repositories from the task and actual callers."])
            lines.extend(["", "## Verification guidance", ""])
            lines.extend([f"- {check}" for check in route["checks"]] or ["Follow affected repository checks."])
            lines.extend(["", GUIDANCE, ""])
            result[path] = "\n".join(lines)
            when = "; ".join(route["when"]).replace("|", "\\|")
            map_lines.append(f"| [{route['title']}](routes/{route_id}.md) | {when} |")
        result["appchi-design/context/map.md"] = "\n".join(map_lines) + "\n"
        return result

    def generated(self, *, write=False):
        documents = self.generated_documents()
        errors, writes = [], []
        for relative, content in documents.items():
            path = safe_path(self.workspace, relative, must_exist=False)
            if path.exists():
                if not path.is_file():
                    fail(f"Generated target is not a regular file: {relative}")
                current = path.read_text(encoding="utf-8")
                if GENERATED not in current:
                    fail(f"Refusing to overwrite unowned file: {relative}")
                if current == content:
                    continue
            if write:
                writes.append((path, content))
            else:
                errors.append(f"Generated navigation drift: {relative}; run context.py render")
        route_dir = safe_path(self.workspace, "appchi-design/context/routes/placeholder.md", must_exist=False).parent
        if route_dir.exists():
            for path in route_dir.glob("*.md"):
                relative = path.relative_to(self.workspace).as_posix()
                safe_path(self.workspace, relative)
                if relative not in documents and GENERATED in path.read_text(encoding="utf-8"):
                    errors.append(f"Stale generated route: {relative}; review and remove it explicitly")
        if errors:
            fail("\n".join(errors))
        # Preflight all ownership/path/drift checks before any writes.
        for path, content in writes:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
        return len(documents)

    def check(self, *, skip_generated=False):
        for source_id in self.catalog["sources"]:
            self.source(source_id)
        cases = self.evaluations()
        generated = None if skip_generated else self.generated()
        return {"sources": len(self.catalog["sources"]), "routes": len(self.routes),
                "evaluation_cases": cases, "generated_documents": generated,
                "note": "Routing checks test navigation, not agent understanding or task acceptance."}


def plan_markdown(plan):
    lines = ["# Candidate reading plan", "", plan["guidance"], "", f"Status: {plan['status']}", ""]
    lines.extend(f"UNRESOLVED: {item}" for item in plan["unresolved"])
    lines.extend(["", "## Selected routes", ""])
    lines.extend(f"- **{r['id']}**: {r['title']} — {'; '.join(r['reasons'])}" for r in plan["routes"])
    if plan["suggestions"]:
        lines.extend(["", "## Other candidates to assess (not selected)", ""])
        lines.extend(f"- {r['id']}: {'; '.join(r['reasons'])}" for r in plan["suggestions"])
    lines.extend(["", "## Required reading pointers", "",
                  "Run the read commands below from appchi-delivery in the selected workspace.", ""])
    for source in plan["sources"]:
        lines.extend([f"- **{source['id']}** ({source['authority']}): `{source['path']}`",
                      f"  - Required by: {', '.join(source['required_by'])}. Preamble required.",
                      f"  - SHA-256: `{source['sha256']}`"])
        lines.extend([f"  - Lines {s['line']}–{s['end_line']}: {s['title']}" for s in source["sections"]]
                     or ["  - Read the full source."])
        lines.append(f"  - Read: `python scripts/context.py read --source {source['id']}`")
    lines.extend(["", "## Conditional expansion", ""])
    lines.extend(f"- From {item['from']}, when {item['when']}: {item['route']}"
                 + (" (already selected)" if item["already_selected"] else " (not selected)")
                 for item in plan["conditional_expansions"])
    lines.extend(["", "## Repositories and verification", "",
                  "Inspect instructions and actual working state: " + ", ".join(plan["repositories"]) + ".", ""])
    lines.extend(f"- {check}" for check in plan["checks"])
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workspace", type=Path, default=Path(__file__).resolve().parents[2])
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("list", help="List route IDs and applicability")
    plan = commands.add_parser("plan", help="Select candidate routes and exact source pointers")
    plan.add_argument("--route", action="append", default=[])
    plan.add_argument("--task", default="")
    plan.add_argument("--path", action="append", default=[])
    plan.add_argument("--format", choices=("markdown", "json"), default="markdown")
    read = commands.add_parser("read", help="Read one catalog source with its scope preamble")
    read.add_argument("--source", required=True)
    check = commands.add_parser("check", help="Validate catalog, sources, evaluations and generated drift")
    check.add_argument("--skip-generated", action="store_true")
    commands.add_parser("render", help="Write deterministic graph-friendly Markdown navigation")
    args = parser.parse_args(argv)
    try:
        context = Context(args.workspace)
        if args.command == "list":
            for route in context.routes.values():
                print(f"{route['id']}: {route['title']} — {'; '.join(route['when'])}")
        elif args.command == "plan":
            result = context.plan(routes=args.route, task=args.task, paths=args.path)
            print(json.dumps(result, ensure_ascii=False, indent=2) if args.format == "json" else plan_markdown(result))
            return 2 if result["unresolved"] else 0
        elif args.command == "read":
            result = context.source(args.source)
            print(f"Source: {result['id']} ({result['authority']})\nPath: {result['path']}\n"
                  f"SHA-256: {result['sha256']}\nIncluded line ranges: {result['ranges']}\n")
            print(result["content"])
        elif args.command == "check":
            print(json.dumps(context.check(skip_generated=args.skip_generated), indent=2))
        else:
            print(json.dumps({"generated_documents": context.generated(write=True)}, indent=2))
        return 0
    except (ContextError, OSError, UnicodeError) as exc:
        print(f"Context error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    # Keep redirected plans/excerpts lossless on Windows legacy code pages too.
    sys.stdout.reconfigure(encoding="utf-8")
    sys.stderr.reconfigure(encoding="utf-8")
    raise SystemExit(main())
