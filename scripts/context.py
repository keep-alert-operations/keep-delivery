INDEX_BEGIN = ("<!-- BEGIN generated context index: edit keep-design/context/task-map.json, "
               "then run context.py render. -->")
INDEX_END = "<!-- END generated context index -->"
INDEX_LINE_LIMIT = 40
COVERS_LIMIT = 160
AUTO_TOPIC_LIMIT = 3
FIND_LIMIT = 8
GENERATED = "<!-- Generated by keep-delivery/scripts/context.py; edit task-map.json instead. -->"
GUIDANCE = (
    "Candidate context only: matching does not establish completeness. Read applicable "
    "workspace/repository instructions, resolve scope corrections, inspect actual code and "
    "callers, and expand when new dependencies or uncertainty appear. Requirements outside "
    "the selected topics remain binding."
)
# Function words carry no subject; question words still drive intent cues.
STOPWORDS = frozenset((
    "a an and any are as at be been being but by can could did do does doing for from get "
    "got has have how i if in into is it its me my no not of on or our should so some than "
    "that the their them then there these they this those to up us was we were what when "
    "where which while who why will with would you your"
).split())
# Conservative stripping so plural and verb forms meet. Matching never uses prefixes,
# so "incidental" stays distinct from "incident".
SUFFIXES = (("ings", ""), ("ing", ""), ("ions", ""), ("ion", ""), ("ments", ""), ("ment", ""),
            ("ors", ""), ("or", ""), ("ers", ""), ("er", ""), ("ies", "y"), ("ied", "y"),
            ("ed", ""), ("es", ""), ("s", ""), ("e", ""))
# Words that open a sentence without changing what it asks for ("Please add …", "Can you fix …").
FILLER = ("please", "kindly", "now", "then", "also", "so", "ok", "okay", "and", "but", "first", "next",
          "finally", "just", "can you", "could you", "would you", "will you", "let's", "we need to",
          "we should", "i want to", "i need to", "i'd like to", "help me", "go ahead and", "try to")
# A failure named inside a supposition ("If the indexer fails, how …?") is not a problem report.
HYPOTHETICAL = ("if", "whether", "unless", "suppose", "in case", "what if")


class ContextError(ValueError):
    """An invalid or unavailable context input; never an empty successful result."""


def fail(message):
    raise ContextError(message)


def relative_path(value):
    if not isinstance(value, str) or not value or "\\" in value:
        fail(f"Expected a workspace-relative POSIX path: {value!r}")
    parts = PurePosixPath(value).parts
    if (value.startswith("/") or ":" in value or any(p in ("..", ".") for p in value.split("/"))
            or not parts or parts[0] not in REPOSITORIES):
        fail(f"Path must stay in a declared Keep repository: {value!r}")
    return parts


def safe_path(workspace, value, *, must_exist=True):
    parts = relative_path(value)
    candidate = workspace.joinpath(*parts)
    resolved = candidate.resolve()
    try:
        resolved.relative_to(workspace / parts[0])
    except ValueError:
        fail(f"Path escapes its declared workspace repository: {value}")
    if must_exist and not resolved.is_file():
        fail(f"Missing or non-regular file: {value}; inspect source indexes and checkout state")
    return resolved


def json_file(workspace, value):
    try:
        return json.loads(safe_path(workspace, value).read_text(encoding="utf-8-sig"))
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        fail(f"Cannot read {value}: {exc}")


def strings(value, label, *, nonempty=False):
    if (not isinstance(value, list) or any(not isinstance(v, str) or not v.strip() for v in value)
            or len(set(value)) != len(value) or (nonempty and not value)):
        fail(f"{label} must be a {'nonempty ' if nonempty else ''}list of unique nonempty strings")


def text(value, label, *, limit=None):
    if not isinstance(value, str) or not value.strip() or (limit and len(value) > limit):
        fail(f"{label} must be nonempty text" + (f" of at most {limit} characters" if limit else ""))


def identifier(value, label):
    if not isinstance(value, str) or not re.fullmatch(r"[a-z0-9]+(?:[-_][a-z0-9]+)*", value):
        fail(f"Invalid {label}: {value!r}")


def words(value):
    return re.findall(r"[a-z0-9]+", unicodedata.normalize("NFKC", value).casefold())


def stem(word):
    for suffix, replacement in SUFFIXES:
        if word.endswith(suffix) and len(word) - len(suffix) >= 3:
            if suffix == "s" and word.endswith(("ss", "us", "is")):
                continue
            return word[:-len(suffix)] + replacement
    return word


def terms(value, *, keep_stopwords=False):
    return [stem(w) for w in words(value) if keep_stopwords or w not in STOPWORDS]


def find_phrase(sequence, phrase):
    """Index of the first contiguous occurrence of phrase in sequence, else None."""
    size = len(phrase)
    return next((i for i in range(len(sequence) - size + 1) if size and sequence[i:i + size] == phrase), None)


def slug(title):
    """GitHub-style Unicode heading anchor, with duplicate suffixes added by headings()."""
    value = re.sub(r"<[^>]+>", "", title)
    value = re.sub(r"!?\[([^\]]+)\]\([^)]*\)", r"\1", value).lower()
    return "".join(
        "-" if ch.isspace() else ch for ch in value
        if ch.isspace() or ch in "-_" or unicodedata.category(ch)[0] in "LNM"
    )


def headings(lines):
    """Parse ATX/setext headings while ignoring fenced and indented code."""
    result, anchors = [], set()
    fence, previous = None, None
    for index, line in enumerate(lines):
        marker = re.match(r"^ {0,3}(`{3,}|~{3,})(.*)$", line.rstrip("\r\n"))
        if fence:
            if (marker and marker[1][0] == fence[0] and len(marker[1]) >= len(fence)
                    and not marker[2].strip()):
                fence = None
            previous = None
            continue
        if marker:
            fence, previous = marker[1], None
            continue
        match = re.match(r"^ {0,3}(#{1,6})(?:[ \t]+(.*?)|[ \t]*)$", line.rstrip("\r\n"))
        underline = re.match(r"^ {0,3}(=+|-+)\s*$", line.rstrip("\r\n"))
        if match:
            level, title, start = len(match[1]), re.sub(r"[ \t]+#+[ \t]*$", "", match[2] or ""), index
        elif underline and previous is not None:
            level, title, start = (1 if underline[1][0] == "=" else 2), previous[1], previous[0]
        else:
            previous = ((index, line.strip()) if line.strip() and not line.startswith(("    ", "\t"))
                        else None)
            continue
        base, suffix = slug(title), 0
        anchor = base
        while anchor in anchors:
            suffix += 1
            anchor = f"{base}-{suffix}"
        anchors.add(anchor)
        result.append({"title": title, "level": level, "start": start, "anchor": anchor})
        previous = None
    for index, heading in enumerate(result):
        heading["end"] = next((h["start"] for h in result[index + 1:]
                               if h["level"] <= heading["level"]), len(lines))
    return result


def merged_ranges(ranges):
    result = []
    for start, end in sorted(ranges):
        if end <= start:
            continue
        if result and start <= result[-1][1]:
            result[-1] = (result[-1][0], max(result[-1][1], end))
        else:
            result.append((start, end))
    return result


def read_lines(path, label):
    try:
        content = path.read_bytes()
        lines = content.decode("utf-8-sig").replace("\r\n", "\n").replace("\r", "\n").splitlines(keepends=True)
    except (OSError, UnicodeError) as exc:
        fail(f"Cannot read {label}: {exc}")
    return content, lines


class Context:
    def __init__(self, workspace):
        self.workspace = Path(workspace).resolve()
        if not self.workspace.is_dir():
            fail(f"Workspace directory does not exist: {workspace}")
        self.catalog = json_file(self.workspace, CATALOG)
        self.validate_schema()

    def validate_schema(self):
        data = self.catalog
        if (not isinstance(data, dict) or type(data.get("schema_version")) is not int
                or data["schema_version"] != SCHEMA_VERSION):
            fail(f"Catalog schema_version must be {SCHEMA_VERSION}")
        if not isinstance(data.get("sources"), dict) or not data["sources"]:
            fail("Catalog sources must be a nonempty object")
        for source_id, source in data["sources"].items():
            identifier(source_id, "source ID")
            if not isinstance(source, dict):
                fail(f"Source {source_id} must be an object")
            relative_path(source.get("path"))
            if not isinstance(source.get("authority"), str) or source["authority"] not in AUTHORITIES:
                fail(f"Source {source_id} has invalid authority")
            strings(source.get("sections"), f"Source {source_id} sections")
            if source.get("include_preamble") is not True:
                fail(f"Source {source_id} must include_preamble: true to preserve scope corrections")
        if not isinstance(data.get("scope_sections"), dict):
            fail("Catalog scope_sections must be an object of document path to headings")
        for path, titles in data["scope_sections"].items():
            relative_path(path)
            strings(titles, f"Scope sections for {path}", nonempty=True)
        if not isinstance(data.get("find_roots"), list) or not data["find_roots"]:
            fail("Catalog find_roots must be a nonempty list")
        for root in data["find_roots"]:
            if not isinstance(root, dict) or root.get("authority") not in AUTHORITIES:
                fail(f"find_roots entry needs a path and valid authority: {root!r}")
            relative_path(root.get("path"))
        strings(data.get("areas"), "Catalog areas", nonempty=True)
        self.validate_intents(data)
        for source_id, source in data["sources"].items():
            if "intents" in source:
                strings(source["intents"], f"Source {source_id} intents", nonempty=True)
                if set(source["intents"]) - set(self.intents):
                    fail(f"Source {source_id} intents name an unknown intent")
        self.validate_topics(data)

    def validate_intents(self, data):
        if not isinstance(data.get("intents"), list) or not data["intents"]:
            fail("Catalog intents must be a nonempty list")
        self.intents = {}
        for intent in data["intents"]:
            if not isinstance(intent, dict):
                fail("Each intent must be an object")
            intent_id = intent.get("id")
            identifier(intent_id, "intent ID")
            if intent_id in self.intents:
                fail(f"Duplicate intent ID: {intent_id}")
            text(intent.get("title"), f"Intent {intent_id} title", limit=40)
            for field in ("cues", "show", "sources", "steps", "skills"):
                strings(intent.get(field), f"Intent {intent_id} {field}", nonempty=field == "steps")
            strings(intent.get("openers", []), f"Intent {intent_id} openers")
            if set(intent["show"]) - SHOW_FIELDS:
                fail(f"Intent {intent_id} show has unknown fields")
            text(intent.get("finish"), f"Intent {intent_id} finish")
            if not isinstance(intent.get("override"), bool):
                fail(f"Intent {intent_id} override must be true or false")
            for source_id in intent["sources"]:
                if source_id not in data["sources"]:
                    fail(f"Intent {intent_id} references unknown source: {source_id}")
            self.intents[intent_id] = intent
        if data.get("default_intent") not in self.intents:
            fail("Catalog default_intent must name an intent")

    def validate_topics(self, data):
        if not isinstance(data.get("topics"), list) or not data["topics"]:
            fail("Catalog topics must be a nonempty list")
        self.topics = {}
        for topic in data["topics"]:
            if not isinstance(topic, dict):
                fail("Each topic must be an object")
            topic_id = topic.get("id")
            identifier(topic_id, "topic ID")
            if topic_id in self.topics:
                fail(f"Duplicate topic ID: {topic_id}")
            text(topic.get("title"), f"Topic {topic_id} title")
            text(topic.get("covers"), f"Topic {topic_id} covers", limit=COVERS_LIMIT)
            if topic.get("area") not in data["areas"]:
                fail(f"Topic {topic_id} has undeclared area {topic.get('area')!r}")
            for field in ("ask_like", "aliases", "path_globs", "requires", "orientation", "sources",
                          "evidence", "repositories", "checks"):
                strings(topic.get(field), f"Topic {topic_id} {field}")
            if not 2 <= len(topic["ask_like"]) <= 4:
                fail(f"Topic {topic_id} needs 2 to 4 ask_like examples")
            for alias in topic["aliases"]:
                if not terms(alias):
                    fail(f"Topic {topic_id} alias {alias!r} has no matchable words")
            for pattern in topic["path_globs"]:
                parts = PurePosixPath(pattern).parts
                if ("\\" in pattern or ":" in pattern or pattern.startswith("/")
                        or any(p in ("..", ".") for p in pattern.split("/"))
                        or not parts or not any(fnmatch.fnmatchcase(repo, parts[0]) for repo in REPOSITORIES)):
                    fail(f"Topic {topic_id} has unsafe path glob: {pattern}")
            for repo in topic["repositories"]:
                if repo not in REPOSITORIES:
                    fail(f"Topic {topic_id} has undeclared repository {repo}")
            if not isinstance(topic.get("related"), list):
                fail(f"Topic {topic_id} related must be a list")
            for item in topic["related"]:
                if not isinstance(item, dict) or not isinstance(item.get("when"), str) or not item["when"].strip():
                    fail(f"Topic {topic_id} related entry needs a condition")
                identifier(item.get("topic"), "related topic")
            self.topics[topic_id] = topic
        for topic in self.topics.values():
            for source_id in topic["orientation"] + topic["sources"] + topic["evidence"]:
                if source_id not in data["sources"]:
                    fail(f"Topic {topic['id']} references unknown source: {source_id}")
            for topic_id in topic["requires"] + [x["topic"] for x in topic["related"]]:
                if topic_id not in self.topics:
                    fail(f"Topic {topic['id']} references unknown topic: {topic_id}")
        self.closure(list(self.topics))

    def closure(self, selected):
        result, active, done = [], set(), set()

        def visit(topic_id):
            if topic_id not in self.topics:
                fail(f"Unknown topic: {topic_id}; use list or find")
            if topic_id in active:
                fail(f"Required-topic cycle involving {topic_id}")
            if topic_id in done:
                return
            active.add(topic_id)
            for dependency in self.topics[topic_id]["requires"]:
                visit(dependency)
            active.remove(topic_id)
            done.add(topic_id)
            result.append(topic_id)

        for topic_id in selected:
            visit(topic_id)
        return result

    def source(self, source_id, *, shown=()):
        """Read a source; ``shown`` lists 0-based line spans of its document already emitted."""
        if source_id not in self.catalog["sources"]:
            fail(f"Unknown source: {source_id}")
        source = self.catalog["sources"][source_id]
        path = safe_path(self.workspace, source["path"])
        content, lines = read_lines(path, f"source {source_id}")
        parsed = headings(lines)

        def unique(title):
            matches = [h for h in parsed if h["title"] == title]
            if len(matches) != 1:
                fail(f"Source {source_id}: heading {title!r} must exist exactly once (found {len(matches)})")
            return matches[0]

        selected = [(unique(title), False) for title in source["sections"]]
        if selected:
            # Document-level scope corrections travel with every partial read of that document.
            chosen = {h["title"] for h, _ in selected}
            selected += [(unique(title), True) for title in self.catalog["scope_sections"].get(source["path"], [])
                         if title not in chosen]
        preamble_end = next((h["start"] for h in parsed if h["level"] == 2), len(lines))
        ranges = ([(0, len(lines))] if not selected else
                  merged_ranges([(0, preamble_end)] + [(h["start"], h["end"]) for h, _ in selected]))
        repeated = {i for start, end in shown for i in range(start, end)}
        shown_above = merged_ranges([(i, i + 1) for start, end in ranges for i in range(start, end) if i in repeated])
        if repeated:
            ranges = merged_ranges([(i, i + 1) for start, end in ranges for i in range(start, end)
                                    if i not in repeated])
        return {
            "id": source_id, "path": source["path"], "authority": source["authority"],
            "sha256": hashlib.sha256(content).hexdigest(), "include_preamble": True,
            "preamble_lines": [1, preamble_end] if preamble_end else [],
            "sections": [{"title": h["title"], "line": h["start"] + 1, "end_line": h["end"],
                          "anchor": h["anchor"], "scope": scope} for h, scope in selected],
            "ranges": [[start + 1, end] for start, end in ranges],
            "shown_above": [[start + 1, end] for start, end in shown_above],
            "content": "\n\n<!-- Unselected sections omitted. -->\n\n".join(
                "".join(lines[start:end]) for start, end in ranges),
        }

    def infer_intent(self, task):
        sequence = terms(task, keep_stopwords=True)
        if not sequence:
            return self.catalog["default_intent"], "no request text; default intent"
        sentences = [(terms(s, keep_stopwords=True), s.rstrip().endswith("?"))
                     for s in re.findall(r"[^.!?\n]+[.!?]*", task)]
        sentences = [(words_, asks) for words_, asks in sentences if words_]
        suppositions = [terms(h, keep_stopwords=True) for h in HYPOTHETICAL]
        reports = [w for w, _ in sentences if not any(w[:len(h)] == h for h in suppositions)]
        for intent in self.intents.values():
            if intent["override"]:
                for cue in intent["cues"]:
                    if any(find_phrase(w, terms(cue, keep_stopwords=True)) is not None for w in reports):
                        return intent["id"], f"cue {cue!r}"
        # An instruction decides next: a sentence opening (after filler) with an intent's opener,
        # or with a cue of an intent other than the default, whose cues also open statements.
        default = self.catalog["default_intent"]
        openers = sorted(((terms(cue, keep_stopwords=True), intent["id"], cue) for intent in self.intents.values()
                          if not intent["override"]
                          for cue in intent.get("openers", []) + (intent["cues"] if intent["id"] != default else [])
                          if cue != "?"), key=lambda item: -len(item[0]))
        filler = [terms(f, keep_stopwords=True) for f in FILLER]
        for words_, _ in sentences:
            stripped = True
            while stripped:
                stripped = next((f for f in filler if len(words_) > len(f) and words_[:len(f)] == f), None)
                words_ = words_[len(stripped):] if stripped else words_
            opener = next((o for o in openers if o[0] and words_[:len(o[0])] == o[0]), None)
            if opener:
                return opener[1], f"sentence opens with {opener[2]!r}"
        asker = next((i["id"] for i in self.intents.values() if "?" in i["cues"]), None)
        if asker and any(asks for _, asks in sentences):
            return asker, "a sentence asks a question"
        earliest = None
        for intent in self.intents.values():
            if intent["override"]:
                continue
            for cue in intent["cues"]:
                position = (len(sequence) if cue == "?" and task.rstrip().endswith("?")
                            else find_phrase(sequence, terms(cue, keep_stopwords=True)))
                if position is not None and (earliest is None or position < earliest[0]):
                    earliest = (position, intent["id"], cue)
        if earliest:
            return earliest[1], f"first cue {earliest[2]!r}"
        return self.catalog["default_intent"], "no intent cue; default intent"

    def match_topics(self, task, paths):
        task_terms = terms(task)
        matches = {}
        for index, (topic_id, topic) in enumerate(self.topics.items()):
            reasons, hits = [], set()
            for alias in topic["aliases"]:
                phrase = tuple(terms(alias))
                if phrase not in hits and find_phrase(task_terms, list(phrase)) is not None:
                    hits.add(phrase)
                    reasons.append(f"Task words: {alias}")
            path_hit = False
            for path in paths:
                for pattern in topic["path_globs"]:
                    if fnmatch.fnmatchcase(path.casefold(), pattern.casefold()):
                        path_hit = True
                        reasons.append(f"Path: {path} matches {pattern}")
            if reasons:
                examples = {t for example in topic["ask_like"] for t in terms(example)}
                matches[topic_id] = {"reasons": reasons, "path": path_hit,
                                     "rank": (-len(hits), -len(examples & set(task_terms)), index)}
        return matches

    def plan(self, *, topics=(), task="", paths=(), intent=None, content=False):
        normalized_paths = []
        for path in paths:
            normalized = path.replace("\\", "/")
            relative_path(normalized)
            safe_path(self.workspace, normalized, must_exist=False)
            normalized_paths.append(normalized)
        if intent is None:
            intent_id, intent_reason = self.infer_intent(task)
        elif intent not in self.intents:
            fail(f"Unknown intent: {intent}; choose one of {', '.join(self.intents)}")
        else:
            intent_id, intent_reason = intent, "explicit"
        chosen = self.intents[intent_id]
        reasons, suggestions = {}, {}
        for topic_id in topics:
            if topic_id not in self.topics:
                fail(f"Unknown topic: {topic_id}; use list or find")
            reasons.setdefault(topic_id, []).append("Explicit topic")
        matches = self.match_topics(task, normalized_paths)
        if topics:
            suggestions = {tid: m["reasons"] for tid, m in matches.items()}
        else:
            ordered = sorted(matches, key=lambda tid: (not matches[tid]["path"], matches[tid]["rank"]))
            for position, topic_id in enumerate(ordered):
                if matches[topic_id]["path"] or position < AUTO_TOPIC_LIMIT:
                    reasons[topic_id] = matches[topic_id]["reasons"]
                else:
                    suggestions[topic_id] = matches[topic_id]["reasons"]
        direct = set(reasons)
        selected = self.closure(reasons)
        for topic_id in selected:
            for required in self.topics[topic_id]["requires"]:
                reasons.setdefault(required, []).append(f"Required by: {topic_id}")
        show = set(chosen["show"])
        # Rank what answers the request ahead of prerequisites: orientation, the requested
        # topics' own sources, scope corrections from required topics (never background),
        # intent additions, then the rest of the required-only topics' sources.
        background = [t for t in selected if t not in direct]
        groups = [("orientation", selected if "orientation" in show else [], "orientation"),
                  ("sources", [t for t in selected if t in direct], "authority"),
                  ("scope", background, "scope"),
                  ("intent", [f"intent:{intent_id}"] if selected else [], "intent"),
                  ("sources", background, "background"),
                  ("evidence", selected if "evidence" in show else [], "evidence")]

        def members(field, owner):
            if field == "intent":
                return chosen["sources"]
            if field == "scope":
                return [s for s in self.topics[owner]["sources"]
                        if self.catalog["sources"][s]["authority"] == "scope"]
            return self.topics[owner][field]

        source_order, used_by, role_of = [], {}, {}
        for field, owners, role in groups:
            for owner in owners:
                for source_id in members(field, owner):
                    if source_id not in used_by:
                        source_order.append(source_id)
                        role_of[source_id] = role
                    if owner not in used_by.setdefault(source_id, []):
                        used_by[source_id].append(owner)
        # Procedure sources limited to other intents stay listed as pointers without text, and
        # with --content each document's preamble and repeated sections appear only once.
        sources, emitted = [], {}
        for source_id in source_order:
            entry = self.catalog["sources"][source_id]
            limited = entry.get("intents")
            if limited and intent_id not in limited:
                source = self.source(source_id)
                source.pop("content")
                source["pointer"] = f"Procedure for {', '.join(limited)} requests; read it when the work becomes one."
            else:
                source = self.source(source_id, shown=emitted.get(entry["path"], ()) if content else ())
                if content:
                    emitted.setdefault(entry["path"], []).extend((start - 1, end) for start, end in source["ranges"])
                else:
                    source.pop("content")
            source["role"], source["required_by"] = role_of[source_id], used_by[source_id]
            sources.append(source)
        repositories, path_globs, checks, related = [], [], [], []
        for topic_id in selected:
            topic = self.topics[topic_id]
            repositories += [r for r in topic["repositories"] if r not in repositories]
            path_globs += [g for g in topic["path_globs"] if g not in path_globs]
            checks += [c for c in topic["checks"] if c not in checks]
            related.extend({"from": topic_id, "when": item["when"], "topic": item["topic"],
                            "already_selected": item["topic"] in selected} for item in topic["related"])
        return {
            "schema_version": SCHEMA_VERSION, "status": "candidate" if selected else "unresolved",
            "task": task, "paths": normalized_paths, "guidance": GUIDANCE,
            "intent": {"id": intent_id, "title": chosen["title"], "reason": intent_reason,
                       "steps": chosen["steps"], "finish": chosen["finish"], "skills": chosen["skills"],
                       "show": chosen["show"]},
            "unresolved": [] if selected else [
                "No topic matched. Choose topics from the index by meaning, inspect the find "
                "candidates and source indexes, or extend the catalog before treating this as sufficient."],
            "topics": [{"id": tid, "title": self.topics[tid]["title"], "covers": self.topics[tid]["covers"],
                        "reasons": reasons[tid]} for tid in selected],
            "suggestions": [{"id": tid, "title": self.topics[tid]["title"], "reasons": why}
                            for tid, why in suggestions.items() if tid not in selected],
            "sources": sources, "repositories": repositories, "path_globs": path_globs,
            "checks": checks, "related": related,
            "candidates": [] if selected or not task.strip() else self.find(task, limit=5),
        }

    def find_documents(self):
        documents = {}
        for root in self.catalog["find_roots"]:
            base = safe_path(self.workspace, root["path"], must_exist=False)
            if base.is_file():
                files = [base]
            elif base.is_dir():
                files = sorted(p for p in base.rglob("*.md") if ".git" not in p.parts)
            else:
                fail(f"find root does not exist: {root['path']}; inspect checkout state")
            for path in files:
                relative = path.relative_to(self.workspace).as_posix()
                documents.setdefault(relative, root["authority"])
        for source in self.catalog["sources"].values():
            documents.setdefault(source["path"], source["authority"])
        return documents

    def citing_sources(self, path, title):
        return [source_id for source_id, source in self.catalog["sources"].items()
                if source["path"] == path and (not source["sections"] or title in source["sections"])]

    def find(self, query, *, limit=FIND_LIMIT):
        wanted = set(terms(query))
        if not wanted:
            return []
        results = []
        for relative, authority in self.find_documents().items():
            path = safe_path(self.workspace, relative)
            _, lines = read_lines(path, relative)
            parsed = headings(lines)
            for index, heading in enumerate(parsed):
                direct_end = parsed[index + 1]["start"] if index + 1 < len(parsed) else len(lines)
                title_hits = wanted & set(terms(heading["title"]))
                body_hits = wanted & set(terms("".join(lines[heading["start"] + 1:direct_end])))
                score = 3 * len(title_hits) + len(body_hits)
                if score:
                    results.append({"path": relative, "title": heading["title"], "line": heading["start"] + 1,
                                    "end_line": heading["end"], "anchor": heading["anchor"],
                                    "authority": authority, "score": score,
                                    "matched": sorted(title_hits | body_hits)})
        results.sort(key=lambda r: (-r["score"], r["path"], r["line"]))
        results = results[:limit]
        for result in results:
            # A cited heading carries its citing source's authority; others keep the document default.
            citing = self.citing_sources(result["path"], result["title"])
            if citing:
                result["authority"] = self.catalog["sources"][citing[0]]["authority"]
            result["topics"] = [topic_id for topic_id, topic in self.topics.items()
                                if set(citing) & set(topic["orientation"] + topic["sources"] + topic["evidence"])]
        return results

    def evaluations(self):
        fixture = json_file(self.workspace, EVALUATIONS)
        if (not isinstance(fixture, dict) or type(fixture.get("schema_version")) is not int
                or fixture["schema_version"] != SCHEMA_VERSION
                or not isinstance(fixture.get("cases"), list) or len(fixture["cases"]) < 20):
            fail(f"Evaluation fixtures need schema_version {SCHEMA_VERSION} and at least 20 cases")
        ids, errors = set(), []
        for case in fixture["cases"]:
            if not isinstance(case, dict):
                fail("Evaluation case must be an object")
            identifier(case.get("id"), "evaluation ID")
            if case["id"] in ids:
                fail(f"Duplicate evaluation ID: {case['id']}")
            ids.add(case["id"])
            if not isinstance(case.get("task"), str):
                fail(f"Evaluation {case['id']} task must be text")
            for field in ("paths", "topics", "must_include_topics", "must_exclude_topics", "must_include_sources"):
                strings(case.get(field), f"Evaluation {case['id']} {field}")
            for field in ("topics", "must_include_topics", "must_exclude_topics"):
                for topic_id in case[field]:
                    if topic_id not in self.topics:
                        fail(f"Evaluation {case['id']} references unknown topic: {topic_id}")
            for source_id in case["must_include_sources"]:
                if source_id not in self.catalog["sources"]:
                    fail(f"Evaluation {case['id']} references unknown source: {source_id}")
            for field in ("intent", "expect_intent"):
                if case.get(field) is not None and case[field] not in self.intents:
                    fail(f"Evaluation {case['id']} references unknown intent: {case[field]}")
            plan = self.plan(topics=case["topics"], task=case["task"], paths=case["paths"],
                             intent=case.get("intent"))
            actual_topics = {t["id"] for t in plan["topics"]}
            actual_sources = {s["id"] for s in plan["sources"]}
            for field, missing in (
                ("missing topics", set(case["must_include_topics"]) - actual_topics),
                ("forbidden topics", set(case["must_exclude_topics"]) & actual_topics),
                ("missing sources", set(case["must_include_sources"]) - actual_sources),
            ):
                if missing:
                    errors.append(f"{case['id']}: {field}: {', '.join(sorted(missing))}")
            if case.get("expect_intent") and plan["intent"]["id"] != case["expect_intent"]:
                errors.append(f"{case['id']}: intent {plan['intent']['id']}, expected {case['expect_intent']}")
            if case.get("expect_status") and plan["status"] != case["expect_status"]:
                errors.append(f"{case['id']}: status {plan['status']}, expected {case['expect_status']}")
            for needle in case.get("must_find", []):
                if not any(needle in f"{c['path']}#{c['title']}" for c in plan["candidates"]):
                    errors.append(f"{case['id']}: no find candidate matches {needle!r}")
        if errors:
            fail("Routing evaluation failed:\n" + "\n".join(errors))
        return len(ids)

    def index_block(self):
        intents = " · ".join(f"`{i['id']}` ({i['title']})" for i in self.intents.values())
        lines = [f"**Intents:** {intents}. Unclear requests start as "
                 f"`{self.catalog['default_intent']}`.", "", "| Area | Topic | Covers |", "|---|---|---|"]
        for area in self.catalog["areas"]:
            lines.extend(f"| {area} | `{t['id']}` | {t['covers'].replace('|', '/')} |"
                         for t in self.topics.values() if t["area"] == area)
        return lines

    def index_document(self):
        path = safe_path(self.workspace, INDEX_TARGET)
        current = path.read_text(encoding="utf-8")
        if current.count(INDEX_BEGIN) != 1 or current.count(INDEX_END) != 1:
            fail(f"{INDEX_TARGET} needs exactly one pair of context index markers")
        before, rest = current.split(INDEX_BEGIN)
        _, after = rest.split(INDEX_END)
        block = self.index_block()
        if len(block) > INDEX_LINE_LIMIT:
            fail(f"Context index has {len(block)} lines; keep it within {INDEX_LINE_LIMIT}")
        return before + INDEX_BEGIN + "\n" + "\n".join(block) + "\n" + INDEX_END + after

    def topic_page(self, topic):
        path = f"{TOPIC_PAGES}/{topic['id']}.md"

        def link_to(source_id):
            source = self.source(source_id)
            link = os.path.relpath(self.workspace / source["path"],
                                   (self.workspace / path).parent).replace("\\", "/")
            return source, quote(link, safe="/.-_")

        lines = ["---", "tags: [context-topic]", f"topic_id: {topic['id']}", f"area: {topic['area']}", "---",
                 "", GENERATED, "", f"# {topic['title']}", "", "[Context map](../map.md)", "",
                 topic["covers"], "", "## Ask like", ""]
        lines.extend(f"- {example}" for example in topic["ask_like"])
        for heading, field in (("Read first", "orientation"), ("Authoritative sources", "sources"),
                               ("Current status and evidence", "evidence")):
            lines.extend(["", f"## {heading}", ""])
            if field == "sources":
                lines.extend(["Include each source's preamble and scope corrections, plus the selected "
                              "sections and their subsections.", ""])
            for source_id in topic[field]:
                source, link = link_to(source_id)
                lines.append(f"- [{source_id}]({link}) — {source['authority']}; preamble required.")
                lines.extend([f"  - [{s['title']}]({link}#{quote(s['anchor'])})"
                              + (" (scope correction)" if s["scope"] else "") for s in source["sections"]]
                             or ["  - Read the full source."])
            if not topic[field]:
                lines.append("None listed; use `context.py find` for dated evidence." if field == "evidence"
                             else "None listed.")
        lines.extend(["", "## Required topics", ""])
        lines.extend([f"- [{self.topics[tid]['title']}]({tid}.md)" for tid in topic["requires"]]
                     or ["No additional topic prerequisites."])
        lines.extend(["", "## Read more when", ""])
        lines.extend([f"- {item['when']} [{self.topics[item['topic']]['title']}]({item['topic']}.md)"
                      for item in topic["related"]] or ["Expand through source indexes if dependencies emerge."])
        lines.extend(["", "## Where the code lives", ""])
        lines.extend([f"- [{repo} instructions](../../../{repo}/AGENTS.md)" for repo in topic["repositories"]]
                     or ["Determine affected repositories from the request and actual callers."])
        lines.extend(f"- `{pattern}`" for pattern in topic["path_globs"])
        lines.extend(["", "## Verification checks", ""])
        lines.extend([f"- {check}" for check in topic["checks"]] or ["Follow affected repository checks."])
        lines.extend(["", GUIDANCE, ""])
        return path, "\n".join(lines)

    def generated_documents(self):
        result = dict(self.topic_page(topic) for topic in self.topics.values())
        lines = ["---", "tags: [context-map]", "---", "", GENERATED, "", "# Keep context map", "",
                 GUIDANCE, "", "Pick an intent for what to do and topics for what to read, then run "
                 "`python scripts/context.py plan --intent INTENT --topic TOPIC --content` from "
                 "keep-delivery. Required links are mandatory; related links say when to read more.", "",
                 "Open the workspace root as an Obsidian vault to include sibling repositories. Graph "
                 "edges alone do not encode the conditions on each topic page.", "",
                 "## Intents", "", "| Intent | For | Finish line |", "|---|---|---|"]
        lines.extend(f"| `{i['id']}` | {i['title']} | {i['finish'].replace('|', '/')} |"
                     for i in self.intents.values())
        lines.extend(["", f"Unclear requests start as `{self.catalog['default_intent']}`.", ""])
        for area in self.catalog["areas"]:
            lines.extend([f"## {area}", "", "| Topic | Covers |", "|---|---|"])
            lines.extend(f"| [{t['title']}](topics/{t['id']}.md) | {t['covers'].replace('|', '/')} |"
                         for t in self.topics.values() if t["area"] == area)
            lines.append("")
        result["keep-design/context/map.md"] = "\n".join(lines)
        result[INDEX_TARGET] = self.index_document()
        return result

    def generated(self, *, write=False):
        documents = self.generated_documents()
        errors, writes = [], []
        for relative, content in documents.items():
            path = safe_path(self.workspace, relative, must_exist=False)
            if path.exists():
                if not path.is_file():
                    fail(f"Generated target is not a regular file: {relative}")
                current = path.read_text(encoding="utf-8")
                if relative != INDEX_TARGET and GENERATED not in current:
                    fail(f"Refusing to overwrite unowned file: {relative}")
                if current == content:
                    continue
            if write:
                writes.append((path, content))
            else:
                errors.append(f"Generated navigation drift: {relative}; run context.py render")
        for directory in (TOPIC_PAGES, "keep-design/context/routes"):
            folder = safe_path(self.workspace, f"{directory}/placeholder.md", must_exist=False).parent
            for path in sorted(folder.glob("*.md")) if folder.exists() else ():
                relative = path.relative_to(self.workspace).as_posix()
                safe_path(self.workspace, relative)
                if relative not in documents and GENERATED in path.read_text(encoding="utf-8"):
                    errors.append(f"Stale generated page: {relative}; review and remove it explicitly")
        if errors:
            fail("\n".join(errors))
        # Preflight all ownership/path/drift checks before any writes.
        for path, content in writes:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
        return len(documents)

    def unowned_spec_sections(self):
        """Level-2 specification sections that no topic's sources reach; a report, not a gate."""
        cited = {}
        for topic in self.topics.values():
            for source_id in topic["orientation"] + topic["sources"] + topic["evidence"]:
                source = self.catalog["sources"][source_id]
                cited.setdefault(source["path"], set()).update(source["sections"] or [None])
        folder = safe_path(self.workspace, f"{SPEC_ROOT}/placeholder.md", must_exist=False).parent
        total, unowned = 0, []
        for path in sorted(folder.glob("*.md")):
            relative = path.relative_to(self.workspace).as_posix()
            parsed = headings(read_lines(path, relative)[1])
            titles = cited.get(relative, set())
            spans = [(h["start"], h["end"]) for h in parsed if h["title"] in titles]
            for heading in (h for h in parsed if h["level"] == 2):
                total += 1
                # A cited ancestor, the section itself or a cited subsection reaches it.
                first, last = heading["start"], heading["end"]
                reached = None in titles or any(start <= first < end or first <= start < last for start, end in spans)
                if not reached:
                    unowned.append(f"{relative} › {heading['title']}")
        return total, unowned

    def check(self, *, skip_generated=False, unowned=False):
        for source_id in self.catalog["sources"]:
            self.source(source_id)
        cases = self.evaluations()
        generated = None if skip_generated else self.generated()
        total, missing = self.unowned_spec_sections()
        result = {"sources": len(self.catalog["sources"]), "topics": len(self.topics),
                  "intents": len(self.intents), "evaluation_cases": cases, "generated_documents": generated,
                  "spec_sections_reached_by_topics": f"{total - len(missing)}/{total}"}
        if unowned:
            result["unowned_spec_sections"] = missing
        result["note"] = "Routing checks test navigation, not agent understanding or task acceptance."
        return result


def plan_markdown(plan):
    intent = plan["intent"]
    show = set(intent["show"])
    lines = ["# Context plan", "", plan["guidance"], "",
             f"Status: {plan['status']} · Intent: `{intent['id']}` — {intent['title']} ({intent['reason']})", ""]
    lines.extend(f"UNRESOLVED: {item}" for item in plan["unresolved"])
    lines.extend(["", "## What to do", ""])
    lines.extend(f"{n}. {step}" for n, step in enumerate(intent["steps"], 1))
    lines.extend(["", f"Finish line: {intent['finish']}"])
    if intent["skills"]:
        lines.append("Skills: " + ", ".join(intent["skills"]))
    lines.extend(["", "## Topics", ""])
    lines.extend(f"- **{t['id']}**: {t['title']} — {'; '.join(t['reasons'])}" for t in plan["topics"])
    if plan["suggestions"]:
        lines.extend(["", "## Other candidates to assess (not selected)", ""])
        lines.extend(f"- {t['id']}: {'; '.join(t['reasons'])}" for t in plan["suggestions"])
    if plan["candidates"]:
        lines.extend(["", "## Sections that share words with the request", ""])
        lines.extend(f"- `{c['path']}` › {c['title']} (lines {c['line']}–{c['end_line']}; {c['authority']}"
                     + (f"; topics: {', '.join(c['topics'])}" if c["topics"] else "") + ")"
                     for c in plan["candidates"])
    lines.extend(["", "## Read", "",
                  "Run the read commands from keep-delivery, or rerun the plan with `--content`.", ""])
    for source in plan["sources"]:
        lines.extend([f"- **{source['id']}** ({source['authority']}; {source['role']}): `{source['path']}`",
                      f"  - Required by: {', '.join(source['required_by'])}. Preamble required.",
                      f"  - SHA-256: `{source['sha256']}`"])
        lines.extend([f"  - Lines {s['line']}–{s['end_line']}: {s['title']}"
                      + (" (scope correction)" if s["scope"] else "") for s in source["sections"]]
                     or ["  - Read the full source."])
        if source.get("pointer"):
            lines.append(f"  - Pointer: {source['pointer']}")
        lines.append(f"  - Read: `python scripts/context.py read --source {source['id']}`")
    if "code" in show and plan["repositories"]:
        lines.extend(["", "## Where the code lives", "",
                      "Read each repository's AGENTS.md before editing: " + ", ".join(plan["repositories"]) + "."])
        lines.extend(f"- `{pattern}`" for pattern in plan["path_globs"])
    if "related" in show and plan["related"]:
        lines.extend(["", "## Read more when", ""])
        lines.extend(f"- From {item['from']}, when {item['when']} → {item['topic']}"
                     + (" (already selected)" if item["already_selected"] else " (not selected)")
                     for item in plan["related"])
    if "checks" in show and plan["checks"]:
        lines.extend(["", "## Verification checks", ""])
        lines.extend(f"- {check}" for check in plan["checks"])
    for source in plan["sources"]:
        if "content" in source:
            lines.extend(["", f"## Source: {source['id']} — `{source['path']}`",
                          f"Included line ranges: {source['ranges']}"])
            if source["shown_above"]:
                lines.append(f"Lines {source['shown_above']} appear under an earlier source of this document.")
            lines.extend(["", source["content"].rstrip("\n")])
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workspace", type=Path, default=Path(__file__).resolve().parents[2])
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("list", help="List intents and topics with what each covers")
    plan = commands.add_parser("plan", help="Select an intent, topics and exact source pointers")
    plan.add_argument("--topic", "--route", dest="topics", action="append", default=[])
    plan.add_argument("--intent")
    plan.add_argument("--task", default="")
    plan.add_argument("--path", action="append", default=[])
    plan.add_argument("--content", action="store_true", help="Include the selected source text")
    plan.add_argument("--format", choices=("markdown", "json"), default="markdown")
    find = commands.add_parser("find", help="Rank headings across specifications, decisions and runbooks")
    find.add_argument("query", nargs="+")
    find.add_argument("--limit", type=int, default=FIND_LIMIT)
    find.add_argument("--format", choices=("markdown", "json"), default="markdown")
    read = commands.add_parser("read", help="Read one catalog source with its scope preamble")
    read.add_argument("--source", required=True)
    check = commands.add_parser("check", help="Validate catalog, sources, evaluations and generated drift")
    check.add_argument("--skip-generated", action="store_true")
    check.add_argument("--unowned", action="store_true",
                       help="List specification sections that no topic's sources reach")
    commands.add_parser("render", help="Write the generated map, topic pages and AGENTS.md index")
    args = parser.parse_args(argv)
    try:
        context = Context(args.workspace)
        if args.command == "list":
            print("Intents:")
            for intent in context.intents.values():
                print(f"  {intent['id']}: {intent['title']} — {intent['finish']}")
            for area in context.catalog["areas"]:
                print(f"{area}:")
                for topic in (t for t in context.topics.values() if t["area"] == area):
                    print(f"  {topic['id']}: {topic['covers']}")
        elif args.command == "plan":
            result = context.plan(topics=args.topics, task=args.task, paths=args.path,
                                  intent=args.intent, content=args.content)
            print(json.dumps(result, ensure_ascii=False, indent=2) if args.format == "json" else plan_markdown(result))
            return 2 if result["unresolved"] else 0
        elif args.command == "find":
            results = context.find(" ".join(args.query), limit=args.limit)
            if args.format == "json":
                print(json.dumps(results, ensure_ascii=False, indent=2))
            else:
                for r in results:
                    print(f"{r['score']:>3}  {r['path']} › {r['title']} (lines {r['line']}–{r['end_line']}; "
                          f"{r['authority']}" + (f"; topics: {', '.join(r['topics'])}" if r["topics"] else "") + ")")
            return 0 if results else 2
        elif args.command == "read":
            result = context.source(args.source)
            print(f"Source: {result['id']} ({result['authority']})\nPath: {result['path']}\n"
                  f"SHA-256: {result['sha256']}\nIncluded line ranges: {result['ranges']}\n")
            print(result["content"])
        elif args.command == "check":
            print(json.dumps(context.check(skip_generated=args.skip_generated, unowned=args.unowned),
                             ensure_ascii=False, indent=2))
        else:
            print(json.dumps({"generated_documents": context.generated(write=True)}, indent=2))
        return 0
    except (ContextError, OSError, UnicodeError) as exc:
        print(f"Context error: {exc}", file=sys.stderr)
        return 1


